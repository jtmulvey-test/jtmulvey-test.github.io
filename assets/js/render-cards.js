/* ------------------------------------------------------------------
   render-cards.js
   Reads data/manifest.json (generated by build.py from content/) and
   builds the research cards. Nothing here is hardcoded per card — add a
   folder, run the build, and it appears.
   ------------------------------------------------------------------ */

(function () {

  var mount = document.getElementById('cards');
  if (!mount) return;

  var MIME = {
    mp4: 'video/mp4', webm: 'video/webm', mov: 'video/quicktime', m4v: 'video/mp4'
  };

  function esc(s) {
    return String(s == null ? '' : s)
      .replace(/&/g, '&amp;').replace(/</g, '&lt;')
      .replace(/>/g, '&gt;').replace(/"/g, '&quot;');
  }

  /* Name -> profile URL, from data/people.json. Filled in before any card
     is built; a missing or malformed file just leaves it empty and every
     credit renders as plain text, which is what it did before this existed. */
  var PEOPLE = {};

  /* Turns a credit value into markup. "Jane Doe, John Roe" becomes two
     lookups, so a slide can credit several people and only the ones with a
     URL on file become links. */
  function creditHTML(value) {
    return String(value == null ? '' : value)
      .split(',')
      .map(function (part) {
        var name = part.trim();
        var url = Object.prototype.hasOwnProperty.call(PEOPLE, name) ? PEOPLE[name] : '';
        if (!name) return '';
        return url
          ? '<a class="card__credit-link" href="' + esc(url) +
            '" target="_blank" rel="noopener">' + esc(name) + '</a>'
          : esc(name);
      })
      .filter(Boolean)
      .join(', ');
  }

  /* Appends the content hash build.py recorded for this file.

     Slide media keeps the same URL forever — slide 2's image is always
     2.png — so replacing or reordering a file leaves browsers serving the
     copy they already cached. The hash makes changed bytes a new URL while
     leaving untouched files on their old one, so a swapped image appears
     immediately and the multi-megabyte videos stay cached across builds.

     Falls back to the bare path when "v" is absent, so a manifest built by
     an older build.py still renders. */
  function versioned(src, v) {
    return v ? src + '?v=' + encodeURIComponent(v) : src;
  }

  function slideMedia(slide) {
    var ext = slide.src.split('.').pop().toLowerCase();
    var src = versioned(slide.src, slide.v);

    if (slide.type === 'video') {
      return '<video data-src="' + esc(src) + '"' +
             ' data-mime="' + (MIME[ext] || '') + '"' +
             (slide.poster
               ? ' poster="' + esc(versioned(slide.poster, slide.poster_v)) + '"'
               : '') +
             ' muted loop playsinline preload="none"' +
             ' aria-label="' + esc(slide.alt || slide.title) + '"></video>';
    }

    return '<img data-src="' + esc(src) + '"' +
           ' alt="' + esc(slide.alt || slide.title) + '"' +
           ' loading="lazy" decoding="async">';
  }

  function cardHTML(card, cardIndex) {
    var slides = card.slides || [];

    var slidesHTML = slides.map(function (slide, i) {
      var text = JSON.stringify({
        title: esc(slide.title),
        journal: esc(slide.journal),
        journal_link: esc(slide.journal_link),
        description: esc(slide.description),
        body_html: slide.body_html || '',
        extra: (slide.extra || []).map(function (f) {
          return { label: esc(f.label), value: creditHTML(f.value) };
        })
      })
        /* The JSON above goes into a single-quoted HTML attribute, and
           card-gallery.js reads it back with JSON.parse. Every value in it
           has already been through esc(), so it contains entities like
           &quot; — and the HTML parser DECODES entities when it reads an
           attribute. Without the &-escape below, a &quot; in the JSON came
           back out of dataset.text as a bare ", which ended the JSON string
           early and made JSON.parse throw. One double quote anywhere in a
           slide's front matter silently broke that slide's text pane.

           Escaping & first turns &quot; into &amp;quot;, which the parser
           decodes back to the literal &quot; that JSON.parse expects and
           that renders as " once card-gallery.js inserts it as HTML. The
           quote escape must stay second, or it would be double-escaped. */
        .replace(/&/g, '&amp;')
        .replace(/'/g, '&#39;');

      return '<div class="card__slide' + (i === 0 ? ' is-active' : '') + '"' +
             " data-text='" + text + "'>" + slideMedia(slide) + '</div>';
    }).join('');

    var dotsHTML = slides.map(function (slide, i) {
      return '<button class="card__dot" type="button" role="tab"' +
             ' aria-selected="' + (i === 0) + '"' +
             ' aria-label="Dataset ' + (i + 1) + ': ' +
             esc(slide.title || 'untitled') + '"></button>';
    }).join('');

    var arrows = slides.length > 1
      ? '<button class="card__arrow card__arrow--prev" type="button" data-dir="prev" aria-label="Previous dataset">' +
          '<svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><path d="M15 18l-6-6 6-6"/></svg>' +
        '</button>' +
        '<button class="card__arrow card__arrow--next" type="button" data-dir="next" aria-label="Next dataset">' +
          '<svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><path d="M9 18l6-6-6-6"/></svg>' +
        '</button>'
      : '';

    var controls = slides.length > 1
      ? '<div class="card__controls">' +
          '<div class="card__dots" role="tablist" aria-label="Datasets">' + dotsHTML + '</div>' +
        '</div>'
      : '';

    /* every card carries the hint, not just the first — a visitor who lands
       mid-page or scrolls past the top card would otherwise never learn the
       media pane holds more than one dataset. They all clear together on the
       first interaction anywhere on the page. */
    var hint = slides.length > 1
      ? '<span class="card__hint">' +
          '<span class="hint--pointer">Click through ' + slides.length + ' datasets &rarr;</span>' +
          '<span class="hint--touch">Swipe to view next</span>' +
        '</span>'
      : '';

    var mediaInner = slides.length
      ? '<div class="card__slides">' + slidesHTML + '</div>' + hint + arrows + controls
      : '<div class="card__placeholder">Drop media into<br><code>content/' +
        esc(card.id) + '/</code></div>';

    return '' +
      '<article class="card" id="' + esc(card.id) + '">' +
        '<div class="card__text">' +
          '<h2 class="card__title">' + esc(card.title) + '</h2>' +
          '<div class="card__slide-text"></div>' +
        '</div>' +
        '<div class="card__media">' + mediaInner + '</div>' +
      '</article>';
  }

  /* ----------------------------------------------------------------
     Deferred loading indicator.

     The manifest is a small JSON file and usually lands in well under a
     second, where a spinner would appear and vanish faster than the eye
     resolves it — which reads as a glitch, not as feedback. So nothing is
     shown at all until one second has passed; past that the wait is long
     enough to need explaining, and the wheel appears.
     ---------------------------------------------------------------- */
  var SPINNER_DELAY = 1000;
  var loadingEl = document.getElementById('cards-loading');

  var spinnerTimer = loadingEl && setTimeout(function () {
    loadingEl.hidden = false;
  }, SPINNER_DELAY);

  /* Called on both success and failure. Every outcome below replaces the
     mount's contents anyway; this just stops a timer that would otherwise
     unhide an element that is about to be discarded. */
  function settled() {
    clearTimeout(spinnerTimer);
  }

  /* people.json is optional: it only decides which credit names are links,
     so a missing or broken one must not take the whole page down with it.
     Both requests go out together — waiting for the manifest first would
     add a round trip to every load for a file that is a few hundred bytes. */
  Promise.all([
    fetch('data/manifest.json', { cache: 'no-cache' })
      .then(function (r) {
        if (!r.ok) throw new Error('manifest.json not found (run: python build.py)');
        return r.json();
      }),
    fetch('data/people.json', { cache: 'no-cache' })
      .then(function (r) { return r.ok ? r.json() : null; })
      .catch(function () { return null; })
  ])
    .then(function (results) {
      settled();
      var data = results[0];
      PEOPLE = (results[1] && results[1].people) || {};
      var cards = data.cards || [];
      if (!cards.length) {
        mount.innerHTML = '<p class="cards__loading">No content folders found.</p>';
        return;
      }

      mount.innerHTML = cards.map(cardHTML).join('');

      mount.querySelectorAll('.card').forEach(function (card) {
        window.LazyMedia.observe(card);
        window.CardGallery(card);
      });
    })
    .catch(function (err) {
      settled();
      mount.innerHTML = '<p class="cards__loading">Could not load research content. ' +
                        esc(err.message) + '</p>';
      console.error(err);
    });
})();
